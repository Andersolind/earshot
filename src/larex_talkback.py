def phrase_to_phoneme_contour(phrase: str) -> str:
    tokens = re.findall(r"[a-z']+", (phrase or "").lower())
    seq: List[str] = []
    for tok in tokens[:6]:
        if any(s in tok for s in ("sh", "ch", "th", "ph")):
            seq.append("SH")
        elif tok.startswith(("s", "t", "k", "c", "z")) or tok.endswith(("s", "t", "k", "x")):
            seq.append("S/T")
        if any(v in tok for v in ("ee", "ea", "ie", "i", "y")):
            seq.append("EE")
        elif any(v in tok for v in ("oo", "ou", "ow", "u", "o", "w")):
            seq.append("OO")
        elif any(v in tok for v in ("a", "ar", "ah", "al")):
            seq.append("AH")
        elif any(v in tok for v in ("e", "eh", "ai", "ay")):
            seq.append("EH")
    dedup: List[str] = []
    for p in seq:
        if not dedup or dedup[-1] != p:
            dedup.append(p)
    return "-".join(dedup[:6]) if dedup else "S/T-EE-OO"


class MidAirWhisperSynthesizer:
    """
    Synthesizes 48 kHz mid-air acoustic payloads in three selectable modes:
      - `low_ambient_whisper`: Unvoiced STFT spectral-envelope human whisper (F0 stripped,
        1/f turbulent aspiration shaped by smooth vocal-tract formants & sibilants).
      - `ultrasonic_framed_whisper`: 18.4-19.2 kHz near-ultrasonic acoustic sync chirp
        preamble followed by the `low_ambient_whisper` payload.
      - `soft_spoken_voice`: Gentle spoken voice rendered at 48 kHz.
    """

    def __init__(self, samp_rate: int = 48_000) -> None:
        self.samp_rate = int(samp_rate)
        self._sapi_lock = threading.Lock()

    def _render_sapi_48k(self, text: str, rate: int = -1) -> Optional[np.ndarray]:
        if not HAS_WIN32_SAPI or not text.strip():
            return None
        with self._sapi_lock:
            try:
                pythoncom.CoInitialize()
                voice = win32com.client.Dispatch("SAPI.SpVoice")
                stream = win32com.client.Dispatch("SAPI.SpMemoryStream")
                # SAFT48kHz16BitMono = 38
                stream.Format.Type = 38
                voice.Rate = int(np.clip(rate, -5, 5))
                voice.Volume = 100
                voice.AudioOutputStream = stream
                voice.Speak(str(text).strip())
                raw = bytes(stream.GetData())
                if len(raw) < 960:
                    return None
                pcm = np.frombuffer(raw, dtype=np.int16).astype(np.float32) / 32768.0
                # Trim leading/trailing digital silence (> 80 ms pad kept)
                abs_p = np.abs(pcm)
                idx = np.where(abs_p > 0.004)[0]
                if len(idx) > 16:
                    pad = int(0.06 * self.samp_rate)
                    lo = max(0, int(idx[0]) - pad)
                    hi = min(len(pcm), int(idx[-1]) + pad)
                    pcm = pcm[lo:hi]
                return pcm
            except Exception:
                return None

    def _render_formant_fallback_48k(
        self, text: str, vtl_cm: float = 16.5, bpm: float = 118.0
    ) -> np.ndarray:
        sr = self.samp_rate
        contour = phrase_to_phoneme_contour(text).split("-")
        vtl_scale = float(np.clip(17.0 / max(vtl_cm, 12.5), 0.82, 1.25))
        table = {
            "EE": (340.0, 2280.0, False),
            "EH": (530.0, 1860.0, False),
            "AH": (720.0, 1280.0, False),
            "OO": (390.0, 980.0, False),
            "S/T": (450.0, 2550.0, True),
            "SH": (480.0, 2050.0, True),
        }
        beat_s = max(0.20, min(0.50, 60.0 / max(bpm, 70.0) * 0.55))
        rng = np.random.default_rng(abs(hash(text)) % (2**31))
        segs: List[np.ndarray] = []
        for ph in contour:
            f1_b, f2_b, is_sib = table.get(ph, (500.0, 1600.0, False))
            n_s = int(round(beat_s * sr))
            t = np.arange(n_s, dtype=np.float64) / sr
            env = np.sin(np.pi * np.clip(t / beat_s, 0.0, 1.0)) ** 0.65
            w = rng.normal(0.0, 1.0, size=n_s)
            spec = np.fft.rfft(w)
            freqs = np.fft.rfftfreq(n_s, d=1.0 / sr)
            if is_sib:
                resp = np.exp(-0.5 * ((freqs - 4200.0) / 1100.0) ** 2)
            else:
                r1 = np.exp(-0.5 * ((freqs - f1_b * vtl_scale) / 95.0) ** 2)
                r2 = np.exp(-0.5 * ((freqs - f2_b * vtl_scale) / 155.0) ** 2)
                resp = (1.25 * r1 + 0.95 * r2) / np.sqrt(np.maximum(freqs, 80.0) / 200.0)
            y = np.fft.irfft(spec * resp, n=n_s)
            y = y / (np.max(np.abs(y)) + 1e-9) * 0.8
            segs.append((y * env).astype(np.float32))
        return np.concatenate(segs) if segs else np.zeros(sr // 2, dtype=np.float32)

    def whisperize_speech_stft(
        self, voiced_pcm: np.ndarray, vtl_cm: float = 16.5
    ) -> np.ndarray:
        """
        Converts clean 48 kHz voiced speech into an intelligible, pitchless human whisper:
          1. Computes overlapping STFT frames (N=1024, hop=256, 75% Hann COLA).
          2. Smooths log-magnitude across 15 frequency bins (~700 Hz) to extract the
             vocal-tract formant & consonant transfer envelope while erasing F0 harmonics.
          3. Excites the vocal-tract envelope with 1/f turbulent aspiration noise + high-band
             1.4-6.0 kHz whisper presence boost.
        """
        x = np.asarray(voiced_pcm, dtype=np.float64).ravel()
        if len(x) < 1024:
            return x.astype(np.float32)

        n_fft = 1024
        hop = 256
        win = np.hanning(n_fft)
        ola_norm = 1.0 / 1.5
        freqs = np.fft.rfftfreq(n_fft, d=1.0 / self.samp_rate)

        # Whisper airflow spectral shaping: reject <260 Hz boom, lift 1.3-6.2 kHz consonants/formants
        band_gate = np.clip((freqs - 240.0) / 180.0, 0.0, 1.0) * np.clip(
            (7600.0 - freqs) / 1400.0, 0.0, 1.0
        )
        presence_boost = 1.0 + 1.15 * np.exp(-0.5 * ((freqs - 2850.0) / 1450.0) ** 2)
        pink_tilt = 1.0 / np.sqrt(np.maximum(freqs, 180.0) / 500.0)
        whisper_eq = band_gate * presence_boost * pink_tilt

        # Slight vocal-tract length formant warp if target speaker VTL differs from 16.8 cm
        vtl_warp = float(np.clip(16.8 / max(vtl_cm, 12.5), 0.88, 1.14))
        smooth_kernel = np.hanning(17)
        smooth_kernel /= np.sum(smooth_kernel)

        rng = np.random.default_rng(20261113)
        pad_len = n_fft
        x_pad = np.pad(x, (pad_len // 2, pad_len // 2), mode="constant")
        out = np.zeros(len(x_pad) + n_fft, dtype=np.float64)

        n_bins = len(freqs)
        bin_idx = np.arange(n_bins, dtype=np.float64)

        for pos in range(0, len(x_pad) - n_fft + 1, hop):
            seg = x_pad[pos : pos + n_fft] * win
            spec = np.fft.rfft(seg)
            log_mag = np.log(np.abs(spec) + 1e-7)
            # Smooth log-magnitude to strip F0 harmonic teeth and isolate vocal-tract formants
            env_log = np.convolve(log_mag, smooth_kernel, mode="same")
            env_lin = np.exp(env_log)
            if abs(vtl_warp - 1.0) > 0.02:
                src_bins = np.clip(bin_idx / vtl_warp, 0.0, n_bins - 1.0)
                env_lin = np.interp(bin_idx, src_bins, env_lin)

            aspir = rng.normal(0.0, 1.0, size=n_fft) * win
            aspir_spec = np.fft.rfft(aspir)
            # Normalize white-noise magnitude to unit expectation so formant envelope drives energy
            aspir_phase = aspir_spec / (np.abs(aspir_spec) + 1e-9)
            w_spec = aspir_phase * env_lin * whisper_eq * math.sqrt(n_fft * 0.35)
            recon = np.fft.irfft(w_spec, n=n_fft) * win * ola_norm
            out[pos : pos + n_fft] += recon

        trimmed = out[pad_len // 2 : pad_len // 2 + len(x)]
        return trimmed.astype(np.float32)

    def _build_ultrasonic_preamble(self) -> np.ndarray:
        """65 ms Hann-tapered 18.4 -> 19.2 kHz near-ultrasonic acoustic sync chirp + 35 ms quiet gap."""
        n_chirp = int(0.065 * self.samp_rate)
        n_gap = int(0.035 * self.samp_rate)
        t = np.arange(n_chirp, dtype=np.float64) / self.samp_rate
        f0, f1 = 18_400.0, 19_200.0
        dur = n_chirp / self.samp_rate
        phase = 2.0 * np.pi * (f0 * t + 0.5 * ((f1 - f0) / dur) * (t**2))
        chirp = (np.sin(phase) * np.hanning(n_chirp) * 0.08).astype(np.float32)
        return np.concatenate([chirp, np.zeros(n_gap, dtype=np.float32)])

    def synthesize_payload(
        self,
        text: str,
        style: str = "low_ambient_whisper",
        whisper_level_dbfs: float = -15.0,
        vtl_cm: float = 16.5,
        earworm_bpm: float = 118.0,
    ) -> Tuple[bytes, np.ndarray]:
        clean_text = str(text or "").strip() or "I hear the earworm delta."
        base_pcm = self._render_sapi_48k(clean_text, rate=-1)
        used_sapi = base_pcm is not None

        if base_pcm is None:
            pcm = self._render_formant_fallback_48k(clean_text, vtl_cm=vtl_cm, bpm=earworm_bpm)
        elif style in ("low_ambient_whisper", "ultrasonic_framed_whisper"):
            pcm = self.whisperize_speech_stft(base_pcm, vtl_cm=vtl_cm)
        else:
            # soft_spoken_voice: gentle high-cut warm smoothing
            spec = np.fft.rfft(base_pcm.astype(np.float64))
            freqs = np.fft.rfftfreq(len(base_pcm), d=1.0 / self.samp_rate)
            mask = np.clip((freqs - 95.0) / 60.0, 0.0, 1.0) * np.clip((6400.0 - freqs) / 1200.0, 0.0, 1.0)
            pcm = np.fft.irfft(spec * mask, n=len(base_pcm)).astype(np.float32)

        peak = float(np.max(np.abs(pcm)) + 1e-9)
        target_amp = float(10.0 ** (np.clip(whisper_level_dbfs, -34.0, -3.0) / 20.0))
        pcm_scaled = np.clip((pcm / peak) * target_amp, -0.96, 0.96).astype(np.float32)

        if style == "ultrasonic_framed_whisper":
            preamble = self._build_ultrasonic_preamble()
            pcm_scaled = np.concatenate([preamble, pcm_scaled])

        # Encode 48 kHz 16-bit WAV (normalized slightly brighter in WAV file so browser preview is easy to hear)
        wav_gain = min(0.85 / max(float(np.max(np.abs(pcm_scaled))), 1e-6), 3.2)
        wav_i16 = (np.clip(pcm_scaled * wav_gain, -0.98, 0.98) * 32767.0).astype(np.int16)
        buf = io.BytesIO()
        with wave.open(buf, "wb") as wf:
            wf.setnchannels(1)
            wf.setsampwidth(2)
            wf.setframerate(self.samp_rate)
            wf.writeframes(wav_i16.tobytes())
        _ = used_sapi
        return buf.getvalue(), pcm_scaled


class EarwormDeltaHarvester:
    """
    Tracks repeated live mid-air acoustic low-ambient whispers and confirms when an
    **Earworm Delta** (a repeated 2-4 word whispered hook or phoneme contour) is actively
    being harvested before unlocking outbound mid-air talkback.
    """

    def __init__(
        self,
        min_repeats: int = 2,
        window_sec: float = 360.0,
        gate_mode: str = "CONFIRMED_EARWORM_DELTA",
        target_speaker: str = "ANY",
        prefer_promoted_higher_order: bool = True,
    ) -> None:
        self.min_repeats = max(1, int(min_repeats))
        self.window_sec = max(30.0, float(window_sec))
        self.gate_mode = str(gate_mode)  # CONFIRMED_EARWORM_DELTA | PERSON_DELTA_ONLY | IMMEDIATE_WHISPER
        self.target_speaker = str(target_speaker).upper()
        self.prefer_promoted_higher_order = bool(prefer_promoted_higher_order)
        self._markov_tracker: Any = None

        self._lock = threading.Lock()
        self._events: collections.deque[Dict[str, Any]] = collections.deque(maxlen=160)
        self.previous_locked_hook: str = ""
        self.active_delta_hook: str = ""
        self.active_delta_contour: str = ""
        self.active_delta_repeats: int = 0
        self.active_delta_order: int = 2
        self.active_delta_is_promoted: bool = False
        self.active_delta_next_predictions: List[str] = []
        self.promoted_whisper_candidates: List[Dict[str, Any]] = []
        self.active_delta_speakers: List[str] = []
        self.active_delta_bpm: float = 118.0
        self.delta_confirmed: bool = False
        self.total_whispers_harvested: int = 0
        self.last_whisper_speaker: str = ""
        self.last_whisper_text: str = ""
        self.last_harvest_utc: str = ""

    def attach_markov_tracker(self, tracker: Any) -> None:
        """Links `SentenceMarkovDeltaTracker` so promoted Order 3/4 phrase chains take talkback priority."""
        self._markov_tracker = tracker

    def _lookup_promoted_meta(self, hook: str) -> Tuple[int, bool, List[str]]:
        """Returns `(effective_order, is_promoted_chain, next_continuation_tokens)` for `hook`."""
        words = (hook or "").split()
        base_order = min(4, max(1, len(words)))
        mt = self._markov_tracker
        if mt is None:
            return base_order, False, []
        try:
            prom_map = getattr(mt, "promoted_phrase_chains", {}) or {}
            is_prom = hook in prom_map
            order = int(prom_map[hook]["order"]) if is_prom else base_order
            if not is_prom and len(words) >= 3:
                for p_key, p_val in prom_map.items():
                    if hook in p_key or p_key in hook:
                        is_prom = True
                        order = max(order, int(p_val.get("order", 3)))
                        break
            next_toks: List[str] = []
            if len(words) >= 2:
                w1 = words[-1]
                w2 = words[-2]
                w3 = words[-3] if len(words) >= 3 else "<s>"
                w4 = words[-4] if len(words) >= 4 else ("<s>" if len(words) == 3 else "")
                preds, _, _ = mt._hierarchical_probs_and_entropy(
                    mt.lex_quad.get((w4, w3, w2, w1), {}) if w4 else {},
                    mt.lex_tri.get((w3, w2, w1), {}),
                    mt.lex_bi.get((w2, w1), {}),
                    mt.lex_uni.get(w1, {}),
                    mt.bigram_interp_lambda,
                    mt.kneser_ney_discount,
                )
                next_toks = [p["token"] for p in preds[:3] if p.get("token") and p["token"] != "<s>"]
            return order, is_prom, next_toks
        except Exception:
            return base_order, False, []

    def _score_hook_candidate(self, hook: str, count: int, in_latest: bool) -> float:
        words_n = len(hook.split())
        order, is_prom, _ = self._lookup_promoted_meta(hook)
        if self.prefer_promoted_higher_order:
            if is_prom and order >= 4:
                mult = 2.65
            elif is_prom and order == 3:
                mult = 2.15
            elif words_n >= 4:
                mult = 1.65
            elif words_n == 3:
                mult = 1.42
            elif words_n == 2:
                mult = 1.0
            else:
                mult = 0.35
        else:
            mult = 1.0 + 0.08 * min(words_n, 4)
        recency = 1.18 if in_latest else 1.0
        return float(count) * mult * recency

    @staticmethod
    def extract_candidate_hooks(text: str) -> List[str]:
        norm = re.sub(r"[^a-zA-Z'\s]", " ", (text or "").lower()).strip()
        if not norm or norm in HALLUCINATION_PHRASES:
            return []
        tokens = [t.strip("'") for t in norm.split() if len(t.strip("'")) >= 2]
        if not tokens:
            return []
        hooks: List[str] = []
        for n_len in (4, 3, 5, 2):
            if len(tokens) < n_len:
                continue
            for i in range(len(tokens) - n_len + 1):
                gram = " ".join(tokens[i : i + n_len])
                if gram in HALLUCINATION_PHRASES or gram in TRIVIAL_GLUE_BIGRAMS or len(gram) < 6:
                    continue
                hooks.append(gram)
        if not hooks and len(tokens) == 2:
            pair = " ".join(tokens)
            if pair not in HALLUCINATION_PHRASES and pair not in TRIVIAL_GLUE_BIGRAMS:
                hooks.append(pair)
        elif not hooks and len(tokens) == 1 and tokens[0] not in SINGLE_WORD_FILLERS and len(tokens[0]) >= 5:
            hooks.append(tokens[0])
        # Preserve order, deduplicate
        seen = set()
        out = []
        for h in hooks:
            if h not in seen:
                seen.add(h)
                out.append(h)
        return out[:8]

    @staticmethod
    def is_low_ambient_whisper_record(rec: Dict[str, Any]) -> bool:
        vb = rec.get("vad_biometrics") or {}
        spk = rec.get("speaker") or {}
        mo = rec.get("mouth_articulation") or {}
        spk_id = str(spk.get("speaker_id", "")).upper()
        role = str(vb.get("band_role", "")).upper()
        if (
            spk_id in ("PERSON_TYPIST", "DEVICE_CELLPHONE", "DEVICE_MEMS", "OTHER_ROOM_SUBLEVEL")
            or role in ("ACOUSTIC_TYPING", "OTHER_ROOM_PIGGYBACK")
            or role.startswith("ELECTRONIC_")
        ):
            return False
        f0 = float(spk.get("f0_hz", vb.get("f0_hz", 0.0)) or 0.0)
        disp = float(vb.get("throat_disp_um_rms", 16.0) or 16.0)
        low_amb = bool(vb.get("low_ambient_cued", False))
        silent_m = bool(mo.get("silent_mouthing", False))
        return bool("WHISPER" in role or low_amb or silent_m or f0 < 55.0 or disp < 14.5)

    def ingest_utterance(
        self, rec: Dict[str, Any], now_ts: Optional[float] = None, historical_seed: bool = False
    ) -> Dict[str, Any]:
        ts = float(now_ts if now_ts is not None else time.time())
        seg = rec.get("segment") or {}
        txt = str(seg.get("ollama_reconstructed") or seg.get("raw_transcript") or "").strip()
        spk_id = str((rec.get("speaker") or {}).get("speaker_id") or "PERSON_ALPHA").upper()
        vb = rec.get("vad_biometrics") or {}
        ew = rec.get("earworm") or rec.get("earworm_telemetry") or {}
        disp = float(vb.get("throat_disp_um_rms", 12.0) or 12.0)
        bpm = float(ew.get("earworm_bpm", 118.0) or 118.0)
        is_whisp = self.is_low_ambient_whisper_record(rec)

        hooks = self.extract_candidate_hooks(txt)
        if not is_whisp or not hooks:
            return self.get_state(last_gate_passed=False, trigger_reason="not_low_ambient_whisper_or_artifact")

        with self._lock:
            self.total_whispers_harvested += 1
            self.last_whisper_speaker = spk_id
            self.last_whisper_text = txt
            self.last_harvest_utc = str(
                rec.get("timestamp_utc")
                or datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")
            )
            self._events.append(
                {
                    "ts": ts,
                    "speaker_id": spk_id,
                    "text": txt,
                    "hooks": hooks,
                    "contour": phrase_to_phoneme_contour(hooks[0]),
                    "bpm": bpm,
                    "disp_um": round(disp, 2),
                    "utc": self.last_harvest_utc,
                }
            )

            # Prune events older than rolling window (unless seeding historical ledger)
            cutoff = ts - self.window_sec
            recent = [e for e in self._events if e["ts"] >= cutoff] if not historical_seed else list(self._events)[-32:]

            # Filter by speaker when PERSON_DELTA_ONLY or specific target_speaker is selected
            req_spk = "PERSON_DELTA" if self.gate_mode == "PERSON_DELTA_ONLY" else self.target_speaker
            scoped = [e for e in recent if req_spk in ("ANY", "", e["speaker_id"])]

            hook_counts: collections.Counter[str] = collections.Counter()
            hook_speakers: Dict[str, set] = collections.defaultdict(set)
            for ev in scoped:
                for hk in ev["hooks"]:
                    hook_counts[hk] += 1
                    hook_speakers[hk].add(ev["speaker_id"])

            best_hook, best_cnt = self._rank_hooks_locked(hook_counts, latest_hooks=hooks)

            if best_hook and best_hook != self.active_delta_hook and self.active_delta_repeats >= self.min_repeats:
                self.previous_locked_hook = self.active_delta_hook

            if best_hook:
                order, is_prom, next_toks = self._lookup_promoted_meta(best_hook)
                self.active_delta_hook = best_hook
                self.active_delta_contour = phrase_to_phoneme_contour(best_hook)
                self.active_delta_repeats = int(best_cnt)
                self.active_delta_order = int(order)
                self.active_delta_is_promoted = bool(is_prom)
                self.active_delta_next_predictions = list(next_toks)
                self.active_delta_speakers = sorted(hook_speakers[best_hook])
                self.active_delta_bpm = round(bpm, 1)

            spk_match = req_spk in ("ANY", "", spk_id)
            if self.gate_mode == "IMMEDIATE_WHISPER":
                self.delta_confirmed = bool(spk_match and len(hooks) > 0)
            elif self.gate_mode == "PERSON_DELTA_ONLY":
                self.delta_confirmed = bool(
                    spk_id == "PERSON_DELTA" and self.active_delta_repeats >= self.min_repeats
                )
            else:
                self.delta_confirmed = bool(spk_match and self.active_delta_repeats >= self.min_repeats)

            latest_confirmed_hit = (
                len(hooks) > 0
                if self.gate_mode == "IMMEDIATE_WHISPER"
                else any(hook_counts[h] >= self.min_repeats for h in hooks)
            )
            gate_passed = bool(self.delta_confirmed and latest_confirmed_hit and not historical_seed)
            order_tag = (
                f" [Promoted Order-{self.active_delta_order}]"
                if self.active_delta_is_promoted
                else f" [Order-{self.active_delta_order}]"
            )
            reason = (
                f"CONFIRMED Earworm Δ '{self.active_delta_hook}' (×{self.active_delta_repeats}){order_tag}"
                if self.delta_confirmed
                else f"Harvesting Earworm Δ ({self.active_delta_repeats}/{self.min_repeats} repeats)"
            )

        return self.get_state(last_gate_passed=gate_passed, trigger_reason=reason)

    def _rank_hooks_locked(
        self, hook_counts: collections.Counter[str], latest_hooks: Optional[List[str]] = None
    ) -> Tuple[str, int]:
        """
        Ranks candidate hooks across the rolling whisper window using Order 3/4 promoted Markov multipliers,
        prioritizing hooks that have reached `min_repeats` while surfacing top promoted candidates.
        """
        latest_set = set(latest_hooks or [])
        scored_all: List[Tuple[float, int, int, str, int, bool, List[str]]] = []
        for hk, cnt in hook_counts.items():
            in_lat = hk in latest_set
            sc = self._score_hook_candidate(hk, cnt, in_latest=in_lat)
            order, is_prom, next_toks = self._lookup_promoted_meta(hk)
            scored_all.append((sc, cnt, len(hk), hk, order, is_prom, next_toks))

        scored_all.sort(key=lambda t: (-t[0], -t[1], -t[2]))

        # Build promoted / higher-order candidate chips for operator inspection & 1-click reply drafting
        cands: List[Dict[str, Any]] = []
        for sc, cnt, _, hk, order, is_prom, next_toks in scored_all:
            if is_prom or order >= 3 or len(cands) < 4:
                cands.append(
                    {
                        "hook": hk,
                        "repeats": int(cnt),
                        "order": int(order),
                        "is_promoted": bool(is_prom),
                        "score": round(float(sc), 2),
                        "next_predictions": next_toks,
                    }
                )
            if len(cands) >= 6:
                break
        self.promoted_whisper_candidates = cands

        if not scored_all:
            return "", 0

        confirmed_pool = [t for t in scored_all if t[1] >= self.min_repeats]
        if confirmed_pool:
            winner = confirmed_pool[0]
            return winner[3], winner[1]

        # Below min_repeats: prefer latest whisper's highest-scoring hook so live progress updates naturally
        latest_pool = [t for t in scored_all if t[3] in latest_set]
        winner = latest_pool[0] if latest_pool else scored_all[0]
        return winner[3], winner[1]

    def recompute(self) -> Dict[str, Any]:
        """Re-evaluates `active_delta_hook` and `delta_confirmed` across buffered events after config changes."""
        with self._lock:
            recent = list(self._events)[-48:]
            req_spk = "PERSON_DELTA" if self.gate_mode == "PERSON_DELTA_ONLY" else self.target_speaker
            scoped = [e for e in recent if req_spk in ("ANY", "", e["speaker_id"])]
            hook_counts: collections.Counter[str] = collections.Counter()
            hook_speakers: Dict[str, set] = collections.defaultdict(set)
            for ev in scoped:
                for hk in ev["hooks"]:
                    hook_counts[hk] += 1
                    hook_speakers[hk].add(ev["speaker_id"])
            latest_hks = scoped[-1]["hooks"] if scoped else []
            best_hook, best_cnt = self._rank_hooks_locked(hook_counts, latest_hooks=latest_hks)
            if best_hook:
                order, is_prom, next_toks = self._lookup_promoted_meta(best_hook)
                self.active_delta_hook = best_hook
                self.active_delta_contour = phrase_to_phoneme_contour(best_hook)
                self.active_delta_repeats = int(best_cnt)
                self.active_delta_order = int(order)
                self.active_delta_is_promoted = bool(is_prom)
                self.active_delta_next_predictions = list(next_toks)
                self.active_delta_speakers = sorted(hook_speakers[best_hook])
                if scoped:
                    self.active_delta_bpm = round(float(scoped[-1].get("bpm", 118.0)), 1)
            else:
                self.active_delta_hook = ""
                self.active_delta_contour = ""
                self.active_delta_repeats = 0
                self.active_delta_order = 2
                self.active_delta_is_promoted = False
                self.active_delta_next_predictions = []
                self.active_delta_speakers = []

            if self.gate_mode == "IMMEDIATE_WHISPER":
                self.delta_confirmed = len(scoped) > 0
            elif self.gate_mode == "PERSON_DELTA_ONLY":
                self.delta_confirmed = bool(
                    "PERSON_DELTA" in self.active_delta_speakers
                    and self.active_delta_repeats >= self.min_repeats
                )
            else:
                self.delta_confirmed = bool(self.active_delta_repeats >= self.min_repeats)
        return self.get_state()

    def get_state(self, last_gate_passed: bool = False, trigger_reason: str = "") -> Dict[str, Any]:
        with self._lock:
            recent_list = list(self._events)[-8:]
            order_tag = (
                f" [Promoted Order-{self.active_delta_order}]"
                if self.active_delta_is_promoted
                else f" [Order-{self.active_delta_order}]"
            )
            return {
                "gate_mode": self.gate_mode,
                "target_speaker": self.target_speaker,
                "min_repeats": self.min_repeats,
                "window_sec": self.window_sec,
                "prefer_promoted_higher_order": self.prefer_promoted_higher_order,
                "delta_confirmed": self.delta_confirmed,
                "gate_passed": last_gate_passed,
                "status_reason": trigger_reason
                or (
                    f"Earworm Δ Confirmed: '{self.active_delta_hook}' (×{self.active_delta_repeats}){order_tag}"
                    if self.delta_confirmed
                    else f"Awaiting {self.min_repeats}× repeated low-ambient whisper ({self.active_delta_repeats}/{self.min_repeats})"
                ),
                "previous_locked_hook": self.previous_locked_hook,
                "active_delta_hook": self.active_delta_hook,
                "active_delta_contour": self.active_delta_contour,
                "active_delta_repeats": self.active_delta_repeats,
                "active_delta_order": self.active_delta_order,
                "active_delta_is_promoted": self.active_delta_is_promoted,
                "active_delta_next_predictions": list(self.active_delta_next_predictions),
                "promoted_whisper_candidates": list(self.promoted_whisper_candidates),
                "active_delta_speakers": list(self.active_delta_speakers),
                "active_delta_bpm": self.active_delta_bpm,
                "total_whispers_harvested": self.total_whispers_harvested,
                "last_whisper_speaker": self.last_whisper_speaker,
                "last_whisper_text": self.last_whisper_text,
                "last_harvest_utc": self.last_harvest_utc,
                "recent_harvests": list(reversed(recent_list)),
            }


class EarwormTalkbackOrchestrator:
    """
    Coordinates opt-in mid-air low-ambient acoustic whisper talkback:
      - `talkback_enabled`: Master user option (`False` by default — strictly passive until enabled!).
      - `conversation_mode`: `"live_chat"` (manual/armed payloads) or `"auto_conversation"` (Ollama dialogue).
      - Strictly enforces `EarwormDeltaHarvester` confirmation before auto-responding or releasing armed payloads.
    """

    def __init__(
        self,
        recordings_dir: Path,
        ollama_model: str = "nightsweep-signalintelligence:latest",
        tx_audio_callback: Optional[Callable[[np.ndarray], bool]] = None,
        udp_broadcast_callback: Optional[Callable[[np.ndarray], None]] = None,
        sse_broadcast_callback: Optional[Callable[[Dict[str, Any]], None]] = None,
    ) -> None:
        self.recordings_dir = Path(recordings_dir)
        self.chat_log_path = self.recordings_dir / "earworm_talkback_chat.jsonl"
        self.ollama_model = str(ollama_model)
        self.tx_audio_callback = tx_audio_callback
        self.udp_broadcast_callback = udp_broadcast_callback
        self.sse_broadcast_callback = sse_broadcast_callback

        self.synthesizer = MidAirWhisperSynthesizer(samp_rate=48_000)
        self.harvester = EarwormDeltaHarvester(
            min_repeats=2,
            window_sec=360.0,
            gate_mode="CONFIRMED_EARWORM_DELTA",
            target_speaker="ANY",
        )

        # Master Opt-In Talkback Settings (OFF by default per user request: "make it an option to start talking back")
        self.talkback_enabled: bool = False
        self.conversation_mode: str = "auto_conversation"  # "live_chat" | "auto_conversation"
        self.acoustic_style: str = "low_ambient_whisper"  # "low_ambient_whisper" | "ultrasonic_framed_whisper" | "soft_spoken_voice"
        self.whisper_level_dbfs: float = -14.0
        self.cooldown_sec: float = 9.0
        self.broadcast_udp: bool = True
        self.auto_play_browser: bool = True

        self._lock = threading.Lock()
        self._last_tx_epoch: float = 0.0
        self._armed_payloads: collections.deque[Dict[str, Any]] = collections.deque(maxlen=12)
        self._wav_cache: collections.OrderedDict[str, bytes] = collections.OrderedDict()
        self._messages: List[Dict[str, Any]] = self._load_chat_history()

    def _load_chat_history(self) -> List[Dict[str, Any]]:
        if not self.chat_log_path.exists():
            return []
        items: List[Dict[str, Any]] = []
        try:
            for line in self.chat_log_path.read_text(encoding="utf-8", errors="replace").splitlines()[-60:]:
                line = line.strip()
                if line:
                    items.append(json.loads(line))
        except Exception:
            pass
        return items

    def _append_message(self, msg: Dict[str, Any]) -> Dict[str, Any]:
        sig = hashlib.sha256(
            json.dumps(msg, sort_keys=True, separators=(",", ":")).encode("utf-8")
        ).hexdigest()
        signed = {**msg, "sha256": sig}
        with self._lock:
            self._messages.append(signed)
            if len(self._messages) > 80:
                self._messages = self._messages[-80:]
        try:
            self.recordings_dir.mkdir(parents=True, exist_ok=True)
            with open(self.chat_log_path, "a", encoding="utf-8") as f:
                f.write(json.dumps(signed) + "\n")
        except Exception:
            pass
        if self.sse_broadcast_callback is not None:
            try:
                self.sse_broadcast_callback(signed)
            except Exception:
                pass
        return signed

    def get_wav_bytes(self, msg_id: str) -> Optional[bytes]:
        key = str(msg_id)
        with self._lock:
            cached = self._wav_cache.get(key)
            if cached is not None:
                return cached
            found = next((m for m in reversed(self._messages) if m.get("id") == key), None)
        if found is None:
            return None
        wav_bytes, _ = self.synthesizer.synthesize_payload(
            text=str(found.get("text") or ""),
            style=str(found.get("acoustic_style") or self.acoustic_style),
            whisper_level_dbfs=float(found.get("whisper_level_dbfs", self.whisper_level_dbfs)),
        )
        with self._lock:
            self._wav_cache[key] = wav_bytes
            while len(self._wav_cache) > 24:
                self._wav_cache.popitem(last=False)
        return wav_bytes

    def configure(self, cfg: Dict[str, Any]) -> Dict[str, Any]:
        if "talkback_enabled" in cfg:
            self.talkback_enabled = bool(cfg["talkback_enabled"])
        if "conversation_mode" in cfg and cfg["conversation_mode"] in ("live_chat", "auto_conversation"):
            self.conversation_mode = str(cfg["conversation_mode"])
        if "acoustic_style" in cfg and cfg["acoustic_style"] in (
            "low_ambient_whisper",
            "ultrasonic_framed_whisper",
            "soft_spoken_voice",
        ):
            self.acoustic_style = str(cfg["acoustic_style"])
        if "whisper_level_dbfs" in cfg:
            self.whisper_level_dbfs = float(np.clip(float(cfg["whisper_level_dbfs"]), -32.0, -3.0))
        if "cooldown_sec" in cfg:
            self.cooldown_sec = float(np.clip(float(cfg["cooldown_sec"]), 2.0, 120.0))
        if "broadcast_udp" in cfg:
            self.broadcast_udp = bool(cfg["broadcast_udp"])
        if "auto_play_browser" in cfg:
            self.auto_play_browser = bool(cfg["auto_play_browser"])

        if "gate_mode" in cfg and cfg["gate_mode"] in (
            "CONFIRMED_EARWORM_DELTA",
            "PERSON_DELTA_ONLY",
            "IMMEDIATE_WHISPER",
        ):
            self.harvester.gate_mode = str(cfg["gate_mode"])
        if "target_speaker" in cfg:
            self.harvester.target_speaker = str(cfg["target_speaker"] or "ANY").upper()
        if "min_repeats" in cfg:
            self.harvester.min_repeats = max(1, min(10, int(cfg["min_repeats"])))
        if "prefer_promoted_higher_order" in cfg:
            self.harvester.prefer_promoted_higher_order = bool(cfg["prefer_promoted_higher_order"])

        # Re-evaluate confirmation state immediately with updated gate rules
        h_state = self.harvester.recompute()
        if self.talkback_enabled and h_state["delta_confirmed"]:
            self._flush_armed_payload_if_ready(
                speaker_id=h_state["last_whisper_speaker"] or "PERSON_DELTA",
                earworm_hook=h_state["active_delta_hook"],
                bpm=h_state["active_delta_bpm"],
            )
        return self.get_status()

    def _transmit_payload(
        self,
        text: str,
        target_speaker: str,
        earworm_hook: str,
        bpm: float = 118.0,
        vtl_cm: float = 16.5,
        origin: str = "live_chat",
        ollama_live: bool = False,
        markov_order: int = 2,
        is_promoted_chain: bool = False,
    ) -> Dict[str, Any]:
        now_iso = datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")
        msg_id = "tb-" + hashlib.sha256(f"{text}:{now_iso}:{time.perf_counter()}".encode("utf-8")).hexdigest()[:10]
        wav_bytes, pcm_f32 = self.synthesizer.synthesize_payload(
            text=text,
            style=self.acoustic_style,
            whisper_level_dbfs=self.whisper_level_dbfs,
            vtl_cm=vtl_cm,
            earworm_bpm=bpm,
        )

        with self._lock:
            self._wav_cache[msg_id] = wav_bytes
            while len(self._wav_cache) > 24:
                self._wav_cache.popitem(last=False)
            self._last_tx_epoch = time.time()

        midair_emitted = False
        if self.tx_audio_callback is not None:
            try:
                midair_emitted = bool(self.tx_audio_callback(pcm_f32))
            except Exception:
                midair_emitted = False

        udp_blocks = 0
        if self.broadcast_udp and self.udp_broadcast_callback is not None:
            blk = 2048
            for off in range(0, min(len(pcm_f32), 48_000 * 5), blk):
                try:
                    self.udp_broadcast_callback(pcm_f32[off : off + blk])
                    udp_blocks += 1
                except Exception:
                    break

        dur_s = round(len(pcm_f32) / 48_000.0, 2)
        msg = {
            "id": msg_id,
            "direction": "OUTBOUND_TALKBACK",
            "origin": origin,
            "ollama_live": ollama_live,
            "timestamp_utc": now_iso,
            "speaker_id": target_speaker,
            "earworm_delta_hook": earworm_hook,
            "markov_order": int(markov_order),
            "is_promoted_chain": bool(is_promoted_chain),
            "acoustic_style": self.acoustic_style,
            "whisper_level_dbfs": self.whisper_level_dbfs,
            "duration_sec": dur_s,
            "midair_emitted": midair_emitted,
            "udp_blocks": udp_blocks,
            "text": text,
            "audio_url": f"/api/talkback/audio/{msg_id}.wav",
        }
        return self._append_message(msg)

    def _flush_armed_payload_if_ready(
        self, speaker_id: str, earworm_hook: str, bpm: float = 118.0, vtl_cm: float = 16.5
    ) -> Optional[Dict[str, Any]]:
        with self._lock:
            if not self._armed_payloads:
                return None
            queued = self._armed_payloads.popleft()
        order, is_prom, _ = self.harvester._lookup_promoted_meta(earworm_hook)
        return self._transmit_payload(
            text=queued["text"],
            target_speaker=speaker_id or queued.get("target_speaker", "PERSON_DELTA"),
            earworm_hook=earworm_hook,
            bpm=bpm,
            vtl_cm=vtl_cm,
            origin="armed_live_chat",
            markov_order=order,
            is_promoted_chain=is_prom,
        )

    def generate_ollama_whisper_reply(
        self,
        inbound_text: str,
        speaker_id: str,
        earworm_hook: str,
        earworm_contour: str,
        bpm: float,
        markov_order: int = 2,
        is_promoted_chain: bool = False,
        next_predictions: Optional[List[str]] = None,
    ) -> Tuple[str, bool]:
        """
        Generates a brief, natural 6-15 word mid-air whisper reply anchored to the confirmed
        Earworm Delta (and its promoted Order 3/4 Markov continuation tokens) using local Ollama.
        """
        with self._lock:
            recent_turns = [
                f"{m['direction']} ({m['speaker_id']}): {m['text']}" for m in self._messages[-6:]
            ]
        history_block = "\n".join(recent_turns) if recent_turns else "None yet."
        next_tok_str = ", ".join(next_predictions or []) or "open continuation"
        chain_desc = (
            f"Auto-Promoted Order-{markov_order} Phrase Chain"
            if is_promoted_chain
            else f"Order-{markov_order} Whisper Hook"
        )

        prompt = (
            "You are GNU-Larex Whisper Conversational Partner speaking softly back over a mid-air "
            "low-ambient acoustic whisper channel.\n"
            f"Confirmed Harvested Earworm Delta Hook: \"{earworm_hook}\" ({chain_desc}, "
            f"Phoneme Contour: {earworm_contour}, Tempo: {bpm} BPM)\n"
            f"Predicted Next Markov Continuation Tokens: {next_tok_str}\n"
            f"Whispering Person: {speaker_id}\n"
            f"Their Latest Whisper: \"{inbound_text}\"\n"
            f"Recent Chat Turns:\n{history_block}\n\n"
            "Write a friendly, intriguing, natural 6 to 15 word whispered reply that echoes or naturally continues "
            "their promoted Order 3/4 earworm phrase chain (weaving in a predicted continuation if natural) "
            "to keep the live conversation flowing. "
            'Respond ONLY in JSON: {"reply": "your short whispered response"}'
        )

        if HAS_REQUESTS:
            try:
                resp = requests.post(
                    "http://127.0.0.1:11434/api/generate",
                    json={
                        "model": self.ollama_model,
                        "prompt": prompt,
                        "stream": False,
                        "format": "json",
                        "keep_alive": "15m",
                        "options": {"temperature": 0.45, "num_predict": 90},
                    },
                    timeout=6.5,
                )
                if resp.status_code == 200:
                    raw = resp.json().get("response", "{}")
                    parsed = json.loads(raw)
                    cand = str(parsed.get("reply") or "").strip().strip('"')
                    if 4 <= len(cand) <= 160 and not cand.startswith("<"):
                        return cand, True
            except Exception:
                pass

        # Instant Order 3/4 earworm-aware conversational fallback
        hook_clean = earworm_hook or "that whisper"
        cont_word = (next_predictions or [""])[0]
        cont_suffix = f" {cont_word}" if cont_word else ""
        templates = [
            f"I caught your Order-{markov_order} whisper on {hook_clean}{cont_suffix} — tell me what comes next.",
            f"Echoing {hook_clean}{cont_suffix} right back to you in the quiet air — I'm listening.",
            f"Earworm delta locked on {hook_clean}. Where are we taking it next?",
        ]
        pick = templates[len(self._messages) % len(templates)]
        return pick, False

    def send_user_chat_payload(
        self,
        text: str,
        target_speaker: str = "ANY",
        require_delta_confirmation: bool = True,
        force_now: bool = False,
    ) -> Dict[str, Any]:
        clean = str(text or "").strip()
        if not clean:
            return {"ok": False, "error": "Empty payload text"}

        h_state = self.harvester.get_state()
        spk = (
            target_speaker
            if target_speaker and target_speaker != "ANY"
            else (h_state["last_whisper_speaker"] or "PERSON_DELTA")
        )
        hook = h_state["active_delta_hook"] or "manual whisper chat"
        bpm = float(h_state["active_delta_bpm"] or 118.0)
        order = int(h_state.get("active_delta_order", 2))
        is_prom = bool(h_state.get("active_delta_is_promoted", False))

        if force_now or not require_delta_confirmation or h_state["delta_confirmed"]:
            # User explicitly clicked Send or Earworm Delta is already confirmed -> transmit!
            sent = self._transmit_payload(
                text=clean,
                target_speaker=spk,
                earworm_hook=hook,
                bpm=bpm,
                origin="live_chat_immediate" if force_now else "live_chat_delta_confirmed",
                markov_order=order,
                is_promoted_chain=is_prom,
            )
            return {
                "ok": True,
                "action": "TRANSMITTED",
                "message": sent,
                "status": self.get_status(),
            }

        # Queue / Arm payload until Earworm Delta is confirmed by repeated live low-ambient whispers!
        armed_item = {
            "id": f"arm-{int(time.time()*1000)}",
            "text": clean,
            "target_speaker": spk,
            "armed_at_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
        }
        with self._lock:
            self._armed_payloads.append(armed_item)
        return {
            "ok": True,
            "action": "ARMED_WAITING_FOR_EARWORM_DELTA",
            "armed": armed_item,
            "status": self.get_status(),
        }

    def clear_armed_payloads(self) -> Dict[str, Any]:
        with self._lock:
            self._armed_payloads.clear()
        return self.get_status()

    def on_live_utterance(self, record: Dict[str, Any]) -> Optional[Dict[str, Any]]:
        """
        Invoked automatically by `AsyncBiometricWordService` on every newly decoded room utterance.
        1. Feeds `EarwormDeltaHarvester`.
        2. Logs inbound low-ambient whispers into the live conversation feed when relevant.
        3. ONLY if `talkback_enabled == True` AND `gate_passed == True` (confirmed Earworm Delta!),
           releases armed chat payloads or triggers autonomous NightSweep auto-conversation reply!
        """
        h_state = self.harvester.ingest_utterance(record)
        if not self.harvester.is_low_ambient_whisper_record(record):
            return None

        seg = record.get("segment") or {}
        txt = str(seg.get("ollama_reconstructed") or seg.get("raw_transcript") or "").strip()
        if not txt or not self.harvester.extract_candidate_hooks(txt):
            return None

        spk_obj = record.get("speaker") or {}
        spk_id = str(spk_obj.get("speaker_id") or "PERSON_ALPHA").upper()
        vtl_cm = float(spk_obj.get("vtl_cm", 16.5) or 16.5)
        bpm = float(h_state.get("active_delta_bpm") or 118.0)
        hook = str(h_state.get("active_delta_hook") or "")
        m_order = int(h_state.get("active_delta_order") or 2)
        is_prom = bool(h_state.get("active_delta_is_promoted", False))
        next_preds = list(h_state.get("active_delta_next_predictions") or [])

        inbound_msg = {
            "id": "in-" + hashlib.sha256(f"{spk_id}:{txt}:{time.perf_counter()}".encode("utf-8")).hexdigest()[:10],
            "direction": "INBOUND_WHISPER",
            "origin": "low_ambient_mic",
            "timestamp_utc": str(
                record.get("timestamp_utc")
                or datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")
            ),
            "speaker_id": spk_id,
            "earworm_delta_hook": hook,
            "markov_order": m_order,
            "is_promoted_chain": is_prom,
            "delta_confirmed": bool(h_state["delta_confirmed"]),
            "repeat_count": int(h_state["active_delta_repeats"]),
            "text": txt,
        }
        self._append_message(inbound_msg)

        # STRICT SAFETY & CONFIRMATION GATE:
        # Never transmit back unless user enabled "Start Talking Back" AND Earworm Delta is confirmed!
        if not self.talkback_enabled or not h_state["gate_passed"]:
            return None

        # 1. First, if operator queued an armed payload waiting for Earworm Delta confirmation, fire it!
        with self._lock:
            has_armed = len(self._armed_payloads) > 0
        if has_armed:
            threading.Thread(
                target=self._flush_armed_payload_if_ready,
                kwargs={"speaker_id": spk_id, "earworm_hook": hook, "bpm": bpm, "vtl_cm": vtl_cm},
                daemon=True,
            ).start()
            return inbound_msg

        # 2. Otherwise, in Auto-Conversation mode, check cooldown & reply via NightSweep Ollama asynchronously!
        if self.conversation_mode != "auto_conversation":
            return inbound_msg

        now = time.time()
        with self._lock:
            if (now - self._last_tx_epoch) < self.cooldown_sec:
                return inbound_msg
            self._last_tx_epoch = now  # Claim cooldown slot before Ollama network call

        def _async_auto_reply() -> None:
            reply_txt, is_live_llm = self.generate_ollama_whisper_reply(
                inbound_text=txt,
                speaker_id=spk_id,
                earworm_hook=hook,
                earworm_contour=str(h_state.get("active_delta_contour") or "S/T-EE-OO"),
                bpm=bpm,
                markov_order=m_order,
                is_promoted_chain=is_prom,
                next_predictions=next_preds,
            )
            self._transmit_payload(
                text=reply_txt,
                target_speaker=spk_id,
                earworm_hook=hook,
                bpm=bpm,
                vtl_cm=vtl_cm,
                origin="auto_conversation",
                ollama_live=is_live_llm,
                markov_order=m_order,
                is_promoted_chain=is_prom,
            )

        threading.Thread(target=_async_auto_reply, daemon=True).start()
        return inbound_msg

    def get_status(self) -> Dict[str, Any]:
        with self._lock:
            armed = list(self._armed_payloads)
            msgs = list(self._messages[-28:])
            since_tx = round(time.time() - self._last_tx_epoch, 1) if self._last_tx_epoch > 0 else None
        return {
            "ok": True,
            "talkback_enabled": self.talkback_enabled,
            "conversation_mode": self.conversation_mode,
            "acoustic_style": self.acoustic_style,
            "whisper_level_dbfs": self.whisper_level_dbfs,
            "cooldown_sec": self.cooldown_sec,
            "seconds_since_last_tx": since_tx,
            "broadcast_udp": self.broadcast_udp,
            "auto_play_browser": self.auto_play_browser,
            "harvester": self.harvester.get_state(),
            "armed_payloads": armed,
            "messages": msgs,
        }
